-- 1. 롤링페이퍼 메시지 테이블 생성
create table if not exists public.rolling_papers (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  nickname text not null,
  content text not null,
  emoji text default '💌' not null,
  bg_color text default '#fff9c4' not null,
  likes integer default 0 not null
);

-- 2. Row Level Security (RLS) 활성화 (보안 기능)
alter table public.rolling_papers enable row level security;

-- 3. 정책 1: 누구나 모든 메모를 읽을 수 있도록 허용 (SELECT)
create policy "누구나 메모 조회 가능"
  on public.rolling_papers
  for select
  using (true);

-- 4. 정책 2: 누구나 자유롭게 새 메모를 등록할 수 있도록 허용 (INSERT)
create policy "누구나 새 메모 작성 가능"
  on public.rolling_papers
  for insert
  with check (true);

-- 5. 정책 3: 누구나 좋아요(하트)를 누를 수 있도록 허용 (UPDATE)
create policy "누구나 좋아요 업데이트 가능"
  on public.rolling_papers
  for update
  using (true)
  with check (true);

-- 6. 실시간 동기화(Realtime) 활성화 (새 글이 등록되면 새로고침 없이 화면에 즉시 표시)
alter publication supabase_realtime add table public.rolling_papers;

